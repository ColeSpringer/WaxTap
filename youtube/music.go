package youtube

import (
	"slices"
	"strings"
	"time"
	"unicode"
	"unicode/utf8"
)

// Music is what a video states about the one recording it carries. Every field
// is read as stated and nothing is inferred: a title is never split into an
// artist and a track, and a video that states no recording has no Music.
type Music struct {
	// Title is the recording's title. An Art Track's is its video's, whole
	// where YouTube cut the video's at 100 characters; a Music card's can be
	// shorter than the video's, which may add a featured credit or a version.
	Title   string
	Artists []string // credited artists in the order stated; never empty
	Album   string   // the release it is on, or "" when none is stated
	// ReleaseDate is the stated release date, at midnight UTC. It is zero when
	// none is stated, which is every Music read from the watch page and an Art
	// Track whose description has no "Released on:" line.
	ReleaseDate time.Time
	// Copyright is the stated copyright line with its sign, the sound-recording
	// (U+2117) one when both are given, or "" when none is stated.
	Copyright string
	Source    MusicSource // which statement it was read from
}

// MusicSource names the statement a Music was read from, which is how far it
// can be trusted.
type MusicSource uint8

const (
	// MusicFromDescription marks an Art Track's generated description: the
	// label's own metadata for this upload, and the only source of several
	// artists, a release date, and a copyright line. Every client carries it.
	MusicFromDescription MusicSource = iota + 1
	// MusicFromWatchPage marks the watch page's Music card, YouTube's match of
	// the audio to a song. It names one artist and no date, it exists only
	// where a watch-page pass ran, and the song it names can be a shorter
	// title than the video's (the card drops a featured credit or a version).
	MusicFromWatchPage
)

func (s MusicSource) String() string {
	switch s {
	case MusicFromDescription:
		return "description"
	case MusicFromWatchPage:
		return "watch-page"
	default:
		return ""
	}
}

// The fixed text of an Art Track's generated description. YouTube writes it in
// English whatever host language the request names.
const (
	artTrackProvided  = "Provided to YouTube by "
	artTrackSeparator = " \u00b7 "
	artTrackReleased  = "Released on:"
	artTrackClosing   = "Auto-generated by YouTube."
	soundCopyright    = "\u2117"
	plainCopyright    = "\u00a9"
)

// A video title holds at most titleLimit characters. YouTube cuts a longer
// Art Track title at a word and closes it with titleCut; the description
// keeps the whole of it.
const (
	titleLimit = 100
	titleCut   = "..."
)

// parseArtTrack reads the description YouTube generates for an Art Track
// upload of the video titled title:
//
//	Provided to YouTube by <provider>
//
//	<Title> * <Artist>[ * <Artist>...]
//
//	<Album>
//
//	[copyright lines, "Released on: YYYY-MM-DD", "Role: Name" credits,
//	"Auto-generated by YouTube."]
//
// where * is U+00B7 with a space each side. It returns nil for anything else.
//
// The three header blocks are strict, since what they yield is written into
// tags, and the title line must open with the video's own title. That anchor
// does two jobs. A title holding the separator would otherwise lose its tail
// to the artist list, and a re-upload that pasted another upload's
// description, which is common, states nothing about this video. The title
// returned is the description's, which is the video's except where YouTube
// cut the video's short (see artTrackCredit). What follows the album is read
// only for the release date and the copyright line; the credits name roles
// in each label's own vocabulary and are passed over.
func parseArtTrack(title, desc string) *Music {
	title = collapseSpace(title)
	if title == "" {
		return nil
	}
	blocks := splitBlocks(desc)
	if len(blocks) < 3 || len(blocks[0]) != 1 || len(blocks[1]) != 1 || len(blocks[2]) != 1 {
		return nil
	}
	if provider, ok := strings.CutPrefix(blocks[0][0], artTrackProvided); !ok || strings.TrimSpace(provider) == "" {
		return nil
	}
	title, artists := artTrackCredit(blocks[1][0], title)
	if artists == nil {
		return nil
	}
	// The album is the third block by position, so only a marked trailer line
	// there says it is missing: an album may read "Words: Subtitle" as a
	// credit does.
	album := blocks[2][0]
	if isArtTrackTrailer(album) {
		return nil
	}

	m := &Music{Title: title, Artists: artists, Album: album, Source: MusicFromDescription}
	var plain string
	for _, block := range blocks[3:] {
		for _, line := range block {
			switch {
			case strings.HasPrefix(line, soundCopyright):
				if m.Copyright == "" {
					m.Copyright = line
				}
			case strings.HasPrefix(line, plainCopyright):
				if plain == "" {
					plain = line
				}
			case strings.HasPrefix(line, artTrackReleased):
				if m.ReleaseDate.IsZero() {
					// A full, real date or nothing: a tag holding half of one
					// would state a precision the description did not.
					v := strings.TrimSpace(strings.TrimPrefix(line, artTrackReleased))
					if d, err := time.Parse("2006-01-02", v); err == nil {
						m.ReleaseDate = d
					}
				}
			}
		}
	}
	if m.Copyright == "" {
		m.Copyright = plain
	}
	return m
}

// artTrackCredit splits a title line into the title it states and the artists
// it credits, given the video title it must open with. It returns no artists
// when the line is not this title's.
//
// The stated title is the video's, or completes it: a video title closed with
// titleCut matches a stated title longer than titleLimit that continues it.
// Short of the limit nothing was cut, so there the dots are the uploader's
// own and only the same title matches.
func artTrackCredit(line, title string) (stated string, artists []string) {
	parts := strings.Split(line, artTrackSeparator)
	for i := range parts {
		parts[i] = strings.TrimSpace(parts[i])
	}
	stem, cut := strings.CutSuffix(title, titleCut)
	stem = strings.TrimSpace(stem)
	// The title is however many leading parts spell the video's title, one
	// unless the title holds the separator itself.
	for k := 1; k < len(parts); k++ {
		stated = collapseSpace(strings.Join(parts[:k], artTrackSeparator))
		completes := cut && utf8.RuneCountInString(stated) > titleLimit && strings.HasPrefix(stated, stem)
		if stated != title && !completes {
			continue
		}
		artists = parts[k:]
		if slices.Contains(artists, "") {
			return "", nil
		}
		return stated, artists
	}
	return "", nil
}

// isArtTrackTrailer reports whether line is one of the marked lines that
// follow the album: a copyright, the release date, or the closing note.
func isArtTrackTrailer(line string) bool {
	return strings.HasPrefix(line, soundCopyright) || strings.HasPrefix(line, plainCopyright) ||
		strings.HasPrefix(line, artTrackReleased) || line == artTrackClosing
}

// splitBlocks splits desc into blank-line separated blocks of trimmed lines.
func splitBlocks(desc string) [][]string {
	desc = strings.NewReplacer("\r\n", "\n", "\r", "\n").Replace(desc)
	var blocks [][]string
	var cur []string
	for line := range strings.SplitSeq(desc, "\n") {
		line = strings.TrimSpace(line)
		if line != "" {
			cur = append(cur, line)
			continue
		}
		if cur != nil {
			blocks = append(blocks, cur)
			cur = nil
		}
	}
	if cur != nil {
		blocks = append(blocks, cur)
	}
	return blocks
}

func collapseSpace(s string) string { return strings.Join(strings.Fields(s), " ") }

// musicCard is the watch page's Music card when it names exactly one song.
type musicCard struct {
	song, artist, album string
}

// cardShelf is one shelf of cards under the description. The Music shelf is
// told from the others (people, places, products) by the icon on its footer
// button, which unlike its "Music" heading does not follow the host language.
type cardShelf struct {
	Cards []struct {
		VideoAttributeViewModel *struct {
			Title             string `json:"title"`    // the song
			Subtitle          string `json:"subtitle"` // its artist
			SecondarySubtitle struct {
				Content string `json:"content"` // its album
			} `json:"secondarySubtitle"`
		} `json:"videoAttributeViewModel"`
	} `json:"cards"`
	FooterButton struct {
		ButtonViewModel struct {
			IconName string `json:"iconName"`
		} `json:"buttonViewModel"`
	} `json:"footerButton"`
}

// descriptionSection is one section of the description in its list layout.
// The details section is a list of labelled rows (date, views, music); the
// album, when the page names one, is a card in a section of its own.
type descriptionSection struct {
	Contents []struct {
		CardViewModel         *albumCard `json:"cardViewModel"`
		LinearLayoutViewModel struct {
			Items []struct {
				ListViewModel listView `json:"listViewModel"`
			} `json:"items"`
		} `json:"linearLayoutViewModel"`
	} `json:"contents"`
}

// listView is a list of rows: the details section's, or a sheet's.
type listView struct {
	ListItems []struct {
		ListItemViewModel listRow `json:"listItemViewModel"`
	} `json:"listItems"`
}

// listRow is one row. In the details section the Music row is told by its
// icon and opens a sheet when tapped; in that sheet a song's row carries its
// cover (an asset) where the actions under the songs carry icons.
type listRow struct {
	Title        viewText `json:"title"`    // the row's label, or a song
	Subtitle     viewText `json:"subtitle"` // a song's artist
	LeadingImage struct {
		Sources []struct {
			CustomImageSource struct {
				YoutubeIconSource struct {
					ClientResource struct {
						Icon string `json:"icon"`
					} `json:"clientResource"`
				} `json:"youtubeIconSource"`
			} `json:"customImageSource"`
		} `json:"sources"`
	} `json:"leadingImage"`
	LeadingImageAccessoryType string `json:"leadingImageAccessoryType"`
	RendererContext           struct {
		CommandContext struct {
			OnTap struct {
				InnertubeCommand struct {
					ShowSheetCommand struct {
						PanelLoadingStrategy struct {
							InlineContent struct {
								SheetViewModel struct {
									Content struct {
										ListViewModel *listView `json:"listViewModel"`
									} `json:"content"`
								} `json:"sheetViewModel"`
							} `json:"inlineContent"`
						} `json:"panelLoadingStrategy"`
					} `json:"showSheetCommand"`
				} `json:"innertubeCommand"`
			} `json:"onTap"`
		} `json:"commandContext"`
	} `json:"rendererContext"`
}

// albumCard is the list layout's album card: the album, then its artist.
type albumCard struct {
	AccessibilityID string `json:"accessibilityId"`
	BodyContent     struct {
		HeroCardBodyViewModel struct {
			BodyContent struct {
				LinearLayoutViewModel struct {
					Items []struct {
						ContentMetadataViewModel struct {
							MetadataRows []struct {
								MetadataParts []struct {
									Text viewText `json:"text"`
								} `json:"metadataParts"`
							} `json:"metadataRows"`
						} `json:"contentMetadataViewModel"`
					} `json:"items"`
				} `json:"linearLayoutViewModel"`
			} `json:"bodyContent"`
		} `json:"heroCardBodyViewModel"`
	} `json:"bodyContent"`
}

// viewText is a text node of the list layout.
type viewText struct {
	Content string `json:"content"`
}

// The marks that tell the music apart from everything else under the
// description. None of them follows the host language, which the labels
// beside them ("Music", "1 song", "Album") do.
const (
	musicShelfIcon = "MUSIC"                                // the Music shelf's footer button
	musicRowIcon   = "YTICON_OUTLINE_MUSIC_VIDEO_S24"       // the details list's Music row
	songRowType    = "LIST_ITEM_IMAGE_ACCESSORY_TYPE_ASSET" // a song's row in that row's sheet
	albumCardID    = "music_album_hero_card"                // the album card
)

// musicCard returns the one song the description names, with ok false when it
// names none or more than one: a video with several is a mix or a
// compilation, which is no single recording.
//
// The song is in whichever layout this response used. The shelf states song,
// artist, and album on one card. The list states song and artist in the sheet
// its Music row opens, and the album on a separate card that names the
// album's artist rather than the song, so that album is taken only when the
// two artists are the same.
func (sd *structuredDescription) musicCard() (card musicCard, ok bool) {
	for _, it := range sd.Items {
		shelf := it.HorizontalCardListRenderer
		if shelf == nil || shelf.FooterButton.ButtonViewModel.IconName != musicShelfIcon {
			continue
		}
		if len(shelf.Cards) != 1 || shelf.Cards[0].VideoAttributeViewModel == nil {
			return musicCard{}, false
		}
		vm := shelf.Cards[0].VideoAttributeViewModel
		return musicCard{song: vm.Title, artist: vm.Subtitle, album: vm.SecondarySubtitle.Content}, true
	}

	var songs []listRow
	var album *albumCard
	for _, it := range sd.Items {
		if it.ItemSectionRenderer == nil {
			continue
		}
		for _, c := range it.ItemSectionRenderer.Contents {
			if c.CardViewModel != nil && c.CardViewModel.AccessibilityID == albumCardID {
				album = c.CardViewModel
			}
			for _, group := range c.LinearLayoutViewModel.Items {
				for _, row := range group.ListViewModel.ListItems {
					if row.ListItemViewModel.icon() == musicRowIcon {
						songs = row.ListItemViewModel.sheetSongs()
					}
				}
			}
		}
	}
	if len(songs) != 1 {
		return musicCard{}, false
	}
	card = musicCard{song: songs[0].Title.Content, artist: songs[0].Subtitle.Content}
	if title, artist := album.rows(); slices.Equal(words(artist), words(card.artist)) {
		card.album = title
	}
	return card, true
}

// icon returns the name of the row's icon, or "" when it leads with anything
// else.
func (r listRow) icon() string {
	for _, src := range r.LeadingImage.Sources {
		if name := src.CustomImageSource.YoutubeIconSource.ClientResource.Icon; name != "" {
			return name
		}
	}
	return ""
}

// sheetSongs returns the songs listed in the sheet the row opens, nil when it
// opens none. An Art Track's Music row is one of those: it states the song
// outright, beside rows for its artist and album, and its description, which
// states more, is what is read.
func (r listRow) sheetSongs() []listRow {
	sheet := r.RendererContext.CommandContext.OnTap.InnertubeCommand.ShowSheetCommand.
		PanelLoadingStrategy.InlineContent.SheetViewModel.Content.ListViewModel
	if sheet == nil {
		return nil
	}
	var songs []listRow
	for _, row := range sheet.ListItems {
		if row.ListItemViewModel.LeadingImageAccessoryType == songRowType {
			songs = append(songs, row.ListItemViewModel)
		}
	}
	return songs
}

// rows returns the album card's two lines, empty for a nil card or one of
// another shape.
func (c *albumCard) rows() (album, artist string) {
	if c == nil {
		return "", ""
	}
	var lines []string
	for _, group := range c.BodyContent.HeroCardBodyViewModel.BodyContent.LinearLayoutViewModel.Items {
		for _, row := range group.ContentMetadataViewModel.MetadataRows {
			if len(row.MetadataParts) > 0 {
				lines = append(lines, row.MetadataParts[0].Text.Content)
			}
		}
	}
	if len(lines) != 2 {
		return "", ""
	}
	return lines[0], lines[1]
}

// contentIDAlbum is the album an asset delivered for Content ID alone carries.
// It names the delivery, not a release.
const contentIDAlbum = "YouTube Content ID"

// music returns the card as the Music of the video titled title on the
// channel named author, or nil when the two do not bear it out.
//
// The card says a song is in the video, which is weaker than saying the video
// is that song: on real pages it has named the karaoke backing a cover was
// sung over, and an unrelated compilation on a lyric video. So it counts only
// when the video's title names the song, and when the artist is the channel's
// own or is named in the title too. Both tests compare whole words, so a
// short name is not found inside a longer one.
func (c musicCard) music(title, author string) *Music {
	song, artist := words(c.song), words(c.artist)
	if len(song) == 0 || len(artist) == 0 {
		return nil
	}
	titleWords := words(title)
	if !hasWords(titleWords, song) {
		return nil
	}
	if !hasWords(titleWords, artist) && !channelOf(author, artist) {
		return nil
	}
	m := &Music{
		Title:   strings.TrimSpace(c.song),
		Artists: []string{strings.TrimSpace(c.artist)},
		Album:   strings.TrimSpace(c.album),
		Source:  MusicFromWatchPage,
	}
	if strings.EqualFold(m.Album, contentIDAlbum) {
		m.Album = ""
	}
	return m
}

// channelOf reports whether the channel named author is the artist's own: it
// names the artist among its words ("Small Artist Official", "Small Artist -
// Topic"), or is the artist's name run together, with or without the VEVO
// suffix those channels carry ("SmallArtistVEVO").
func channelOf(author string, artist []string) bool {
	channel := words(author)
	if hasWords(channel, artist) {
		return true
	}
	joined, name := strings.Join(channel, ""), strings.Join(artist, "")
	return joined == name || joined == name+"vevo"
}

// words splits s into its lowercased runs of letters and digits.
func words(s string) []string {
	return strings.FieldsFunc(strings.ToLower(s), func(r rune) bool {
		return !unicode.IsLetter(r) && !unicode.IsDigit(r)
	})
}

// hasWords reports whether needle occurs in hay as a run of whole words.
func hasWords(hay, needle []string) bool {
	if len(needle) == 0 {
		return false
	}
	for i := 0; i+len(needle) <= len(hay); i++ {
		if slices.Equal(hay[i:i+len(needle)], needle) {
			return true
		}
	}
	return false
}
