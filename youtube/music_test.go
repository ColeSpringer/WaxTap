func day(s string) time.Time {
	d, err := time.Parse("2006-01-02", s)
	if err != nil {
		panic(err)
	}
	return d
}

func TestParseArtTrack(t *testing.T) {
	cases := []struct {
		name  string
		title string
		desc  string
		want  *Music
	}{
		{
			name:  "one artist, release date and copyright",
			title: "Night Drive",
			desc:  artTrackOneArtist,
			want: &Music{
				Title: "Night Drive", Artists: []string{"Small Artist"}, Album: "Night Drive EP",
				ReleaseDate: day("2019-03-13"), Copyright: "℗ 2019 Fixture Records",
				Source: MusicFromDescription,
			},
		},
		{
			name:  "several artists and no release date",
			title: "Night Drive (2017 Remaster)",
			desc:  artTrackSeveralArtists,
			want: &Music{
				Title: "Night Drive (2017 Remaster)", Artists: []string{"Small Artist", "Guest Artist"},
				Album:     "A Fixture Box Set (1977 - 1982)",
				Copyright: "℗ 1981, 2017 Fixture Records Ltd, a Fixture Music Group Company",
				Source:    MusicFromDescription,
			},
		},
		{
			name:  "the three header blocks alone",
			title: "Track",
			desc:  artTrackMinimal,
			want:  &Music{Title: "Track", Artists: []string{"Artist"}, Album: "Album", Source: MusicFromDescription},
		},
		{
			// A first-separator split would read the title as "Left" and credit
			// "Right" as an artist; the video's own title says where it ends.
			name:  "a title holding the separator is anchored by the video title",
			title: "Left · Right",
			desc:  "Provided to YouTube by Label\n\nLeft · Right · Artist\n\nAlbum",
			want:  &Music{Title: "Left · Right", Artists: []string{"Artist"}, Album: "Album", Source: MusicFromDescription},
		},
		{
			name:  "whitespace runs do not break the anchor",
			title: "Night  Drive ",
			desc:  strings.Replace(artTrackMinimal, "Track", "Night Drive", 1),
			want:  &Music{Title: "Night Drive", Artists: []string{"Artist"}, Album: "Album", Source: MusicFromDescription},
		},
		{
			name:  "windows line ends",
			title: "Night Drive",
			desc:  strings.ReplaceAll(artTrackOneArtist, "\n", "\r\n"),
			want: &Music{
				Title: "Night Drive", Artists: []string{"Small Artist"}, Album: "Night Drive EP",
				ReleaseDate: day("2019-03-13"), Copyright: "℗ 2019 Fixture Records",
				Source: MusicFromDescription,
			},
		},
		{
			name:  "leading blank lines",
			title: "Track",
			desc:  "\n\n" + artTrackMinimal,
			want:  &Music{Title: "Track", Artists: []string{"Artist"}, Album: "Album", Source: MusicFromDescription},
		},
		{
			name:  "an impossible release date is left out",
			title: "Night Drive",
			desc:  strings.Replace(artTrackOneArtist, "2019-03-13", "2019-02-30", 1),
			want: &Music{
				Title: "Night Drive", Artists: []string{"Small Artist"}, Album: "Night Drive EP",
				Copyright: "℗ 2019 Fixture Records", Source: MusicFromDescription,
			},
		},
		{
			name:  "a year-only release date is left out",
			title: "Night Drive",
			desc:  strings.Replace(artTrackOneArtist, "2019-03-13", "2019", 1),
			want: &Music{
				Title: "Night Drive", Artists: []string{"Small Artist"}, Album: "Night Drive EP",
				Copyright: "℗ 2019 Fixture Records", Source: MusicFromDescription,
			},
		},
		{
			name:  "the sound-recording line outranks the plain copyright",
			title: "Track",
			desc:  artTrackMinimal + "\n\n© 2020 Fixture Publishing\n℗ 2020 Fixture Records",
			want: &Music{
				Title: "Track", Artists: []string{"Artist"}, Album: "Album",
				Copyright: "℗ 2020 Fixture Records", Source: MusicFromDescription,
			},
		},
		{
			name:  "a plain copyright alone is kept",
			title: "Track",
			desc:  artTrackMinimal + "\n\n© 2020 Fixture Publishing",
			want: &Music{
				Title: "Track", Artists: []string{"Artist"}, Album: "Album",
				Copyright: "© 2020 Fixture Publishing", Source: MusicFromDescription,
			},
		},
		{
			name:  "an album titled like a credit",
			title: "Track",
			desc:  strings.Replace(artTrackMinimal, "\n\nAlbum", "\n\nRe: Stacks", 1),
			want:  &Music{Title: "Track", Artists: []string{"Artist"}, Album: "Re: Stacks", Source: MusicFromDescription},
		},

		{
			// YouTube cuts an Art Track's title at a word once it passes 100
			// characters and closes it with three dots; the description keeps
			// the whole of it, which is then the title to report.
			name:  "a title YouTube cut short is completed from the description",
			title: longTitleCut,
			desc:  "Provided to YouTube by Label\n\n" + longTitle + " \u00b7 Artist \u00b7 Other Artist\n\nAlbum",
			want:  &Music{Title: longTitle, Artists: []string{"Artist", "Other Artist"}, Album: "Album", Source: MusicFromDescription},
		},
		{
			name:  "a title that really ends in dots",
			title: "Wait...",
			desc:  strings.Replace(artTrackMinimal, "Track", "Wait...", 1),
			want:  &Music{Title: "Wait...", Artists: []string{"Artist"}, Album: "Album", Source: MusicFromDescription},
		},

		// Shapes that state no track.
		{name: "empty", title: "Track"},
		{
			// Short of 100 characters nothing was cut, so dots are the
			// uploader's and a longer title in the description is another
			// upload's.
			name:  "dots on a short title are not a cut",
			title: "Track...",
			desc:  strings.Replace(artTrackMinimal, "Track", "Track (Extended Mix)", 1),
		},
		{
			name:  "a cut title the description does not continue",
			title: longTitleCut,
			desc:  "Provided to YouTube by Label\n\n" + strings.Replace(longTitle, "Symphony", "Sinfonia", 1) + " \u00b7 Artist\n\nAlbum",
		},
		{name: "blank", title: "Track", desc: "\n \n"},
		{name: "no video title to anchor on", desc: artTrackMinimal},
		{
			name:  "a hand-written description",
			title: "Track",
			desc:  "Official video for Track · Artist\n\nStream it everywhere: https://example.invalid\n\nFollow us",
		},
		{
			// A re-upload that pasted another upload's generated description.
			name:  "a description generated for another title",
			title: "Artist - Track (Lyrics)",
			desc:  artTrackMinimal,
		},
		{
			name:  "a title that only starts like the video's",
			title: "Track",
			desc:  strings.Replace(artTrackMinimal, "Track ·", "Tracking ·", 1),
		},
		{name: "provided line not first", title: "Track", desc: "Our new single!\n\n" + artTrackMinimal},
		{
			name:  "provided line with no provider",
			title: "Track",
			desc:  strings.Replace(artTrackMinimal, "Provided to YouTube by Label", "Provided to YouTube by", 1),
		},
		{
			name:  "missing album block",
			title: "Track",
			desc:  "Provided to YouTube by Label\n\nTrack · Artist\n\n℗ 2020 Label\n\nAuto-generated by YouTube.",
		},
		{
			name:  "the closing note where the album belongs",
			title: "Track",
			desc:  "Provided to YouTube by Label\n\nTrack · Artist\n\nAuto-generated by YouTube.",
		},
		{name: "only the provided and title blocks", title: "Track", desc: "Provided to YouTube by Label\n\nTrack · Artist"},
		{name: "title line with no artist", title: "Track", desc: "Provided to YouTube by Label\n\nTrack\n\nAlbum"},
		{name: "title line with an empty artist", title: "Track", desc: "Provided to YouTube by Label\n\nTrack · \n\nAlbum"},
		{
			name:  "an empty artist between two",
			title: "Track",
			desc:  "Provided to YouTube by Label\n\nTrack · Artist ·  · Other\n\nAlbum",
		},
		{name: "a middot without spaces is not the separator", title: "Track", desc: "Provided to YouTube by Label\n\nTrack·Artist\n\nAlbum"},
		{name: "title block with a second line", title: "Track", desc: "Provided to YouTube by Label\n\nTrack · Artist\nMore text\n\nAlbum"},
		{name: "album block with a second line", title: "Track", desc: "Provided to YouTube by Label\n\nTrack · Artist\n\nAlbum\nCheck out our merch"},
		{name: "provided block with a second line", title: "Track", desc: "Provided to YouTube by Label\nTrack · Artist\n\nAlbum"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := parseArtTrack(c.title, c.desc)
			if !reflect.DeepEqual(got, c.want) {
				t.Fatalf("parseArtTrack = %+v, want %+v", got, c.want)
			}
		})
	}
}

